'use client';

import React, { useState } from 'react';
import type { Signal } from '@/types/api';

const BADGE: Record<Signal['decision'], string> = {
  BUY: 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/30',
  SELL: 'bg-rose-500/20 text-rose-300 border border-rose-500/30',
  HOLD: 'bg-slate-800 text-slate-300 border border-slate-700',
};

export function SignalsTable({ signals }: { signals: Signal[] }) {
  const [expanded, setExpanded] = useState<number | null>(null);

  if (signals.length === 0) {
    return (
      <div className="rounded-2xl border border-slate-800/80 bg-slate-900/40 p-8 text-center space-y-3">
        <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-xl bg-slate-800/60 text-slate-400">
          <svg className="h-6 w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.8} d="M13 10V3L4 14h7v7l9-11h-7z" />
          </svg>
        </div>
        <div className="text-base font-semibold text-slate-200">No Trading Signals Yet</div>
        <p className="text-xs text-slate-400 max-w-sm mx-auto">
          Trading signals generated by model evaluations and strategy rules will appear here.
        </p>
      </div>
    );
  }

  return (
    <div className="rounded-2xl border border-slate-800/80 bg-slate-900/40 overflow-hidden shadow-xl">
      {/* Header */}
      <div className="flex items-center justify-between border-b border-slate-800/80 bg-slate-950/60 px-5 py-4">
        <div className="flex items-center gap-3">
          <h3 className="text-base font-semibold text-white tracking-tight">Strategy Decisions</h3>
          <span className="rounded-full bg-emerald-500/10 border border-emerald-500/30 px-2.5 py-0.5 text-xs font-mono font-medium text-emerald-400">
            {signals.length} Signals
          </span>
        </div>
        <div className="text-xs font-mono text-slate-400">
          Evaluated via Model Conviction
        </div>
      </div>

      {/* Table */}
      <div className="overflow-x-auto">
        <table className="w-full text-sm text-left border-collapse min-w-[650px]">
          <thead>
            <tr className="border-b border-slate-800/80 bg-slate-950/40 text-[11px] font-mono text-slate-400 uppercase tracking-wider">
              <th className="py-3 px-5">Timestamp</th>
              <th className="py-3 px-5">Symbol</th>
              <th className="py-3 px-5">Decision</th>
              <th className="py-3 px-5 text-right">Confidence Score</th>
              <th className="py-3 px-5">Primary Reason</th>
              <th className="py-3 px-5 text-right">Details</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-800/60">
            {signals.map((s) => {
              const reason = (s.rationale as { reason?: string })?.reason ?? 'threshold_pass';
              const isExpanded = expanded === s.id;
              return (
                <React.Fragment key={s.id}>
                  <tr className="hover:bg-slate-800/30 transition-colors">
                    <td className="py-3.5 px-5 font-mono text-xs text-slate-400">
                      {new Date(s.ts).toLocaleString()}
                    </td>
                    <td className="py-3.5 px-5">
                      <span className="inline-flex items-center px-2.5 py-1 rounded-lg bg-emerald-500/10 border border-emerald-500/20 text-emerald-400 font-bold font-mono text-xs">
                        {s.symbol}
                      </span>
                    </td>
                    <td className="py-3.5 px-5">
                      <span className={`inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-mono font-bold ${BADGE[s.decision]}`}>
                        {s.decision}
                      </span>
                    </td>
                    <td className="py-3.5 px-5 text-right font-mono font-semibold text-white">
                      {s.score.toFixed(3)}
                    </td>
                    <td className="py-3.5 px-5 text-xs font-mono text-slate-300">
                      {reason}
                    </td>
                    <td className="py-3.5 px-5 text-right">
                      <button
                        type="button"
                        onClick={() => setExpanded(isExpanded ? null : s.id)}
                        className="text-xs font-mono text-emerald-400 hover:text-emerald-300 hover:underline cursor-pointer transition"
                      >
                        {isExpanded ? 'Hide' : 'Inspect'}
                      </button>
                    </td>
                  </tr>

                  {isExpanded && (
                    <tr>
                      <td colSpan={6} className="bg-slate-950/90 px-6 py-4 border-b border-slate-800/80">
                        <div className="rounded-xl border border-slate-800 bg-[#060910] p-4 text-xs font-mono">
                          <div className="text-[11px] uppercase tracking-wider text-slate-400 mb-2">
                            Decision Evaluation Rationale
                          </div>
                          <pre className="text-emerald-400/90 whitespace-pre-wrap overflow-x-auto text-[11px] leading-relaxed">
                            {JSON.stringify(s.rationale, null, 2)}
                          </pre>
                        </div>
                      </td>
                    </tr>
                  )}
                </React.Fragment>
              );
            })}
          </tbody>
        </table>
      </div>
    </div>
  );
}
